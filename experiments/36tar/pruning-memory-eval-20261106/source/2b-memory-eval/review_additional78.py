def main():
    rows=read(OUT/'additional78.json');byid={q['id']:q for q in rows}
    assert len(D)==78 and {'nextgqa:val:'+x[0] for x in D}==set(byid)
    receipt=read(OUT/'additional78_sheets/receipts.json')
    frames={s['source_path']:{f['frame_id']:f for f in s['frames']} for s in receipt['sources']}
    records=[]
    for tail,kind,ids,note in D:
        q=byid['nextgqa:val:'+tail];w=[frames[q['source_path']][i] for i in ids]
        assert w and all(f['pts_s']<=q['query_time_s'] for f in w)
        records.append(dict(id=q['id'],stratum=kind,note=note,witnesses=w,
            candidate=kind!='S',formal_evaluation_eligible=False,model_outputs_seen=False,
            reviewer='Codex one initial new78 visual pass; not independent human review',
            physical_causal_ground_truth_claimed=False,raw_question_changed=False))
    payload=dict(status='additional78_single_visual_pass_complete',questions=records,
        additional78_sha256=sha(OUT/'additional78.json'),initial_plan_sha256=sha(OUT/'additional78_sheets/initial_review_plan.json'),
        inspected_images={im['path']:sha(ROOT/im['path']) for s in receipt['sources'] for im in s['images']},
        stratum_counts=dict(Counter(q['stratum'] for q in records)),candidates=sum(q['candidate'] for q in records),
        pretrained_loads=0,holdout_images=0,followup_batches=0,
        note='One initial annotation batch for new questions only; no old71 dispositions changed and no quality claims from model answers.')
    save(OUT/'additional78_review.json',payload)
    with (OUT/'新增78题审核.csv').open('w',encoding='utf-8-sig',newline='') as f:
        fields=['id','question','official_answer','stratum','note','candidate'];writer=csv.DictWriter(f,fieldnames=fields);writer.writeheader()
        for q in records:
            r=byid[q['id']];writer.writerow(dict(id=q['id'],question=r['question'],official_answer=r['options'][r['answer_index']],
                stratum=q['stratum'],note=q['note'],candidate=q['candidate']))
    print({k:v for k,v in payload.items() if k not in ['questions','inspected_images','note']})


if __name__=='__main__':main()
